// audit-lectures.js — T-067 step 1. READ-ONLY: it loads the curriculum and the
// lecture summaries, prints every lecture, and lists candidate overlapping pairs
// (within and across courses) for a human to judge. It changes nothing.
//
//   node tools/audit-lectures.js                 > loop/specs/T-067-plan-v2/audit-raw.txt
//   node tools/audit-lectures.js --check-prereqs   (validates prerequisites.json)
//
// Reproducible: no clock, no randomness, no network; the output depends only on
// the files in platform/data/ (and, for --check-prereqs, on prerequisites.json).
//
// Similarity: each lecture becomes a bag of content words from its title,
// summary takeaway and beat titles/text (stop words and LaTeX dropped, a crude
// suffix strip so "derivative"/"derivatives" meet). Words are weighted by
// TF-IDF over all 494 lectures and pairs are ranked by cosine similarity. A high
// score means "the same words carry both lectures", which is a lead, not a
// verdict: two lectures on the chain rule at different levels score high and are
// both core. Every pair listed is judged by hand in audit.md.
"use strict";
const fs = require("fs"), vm = require("vm"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const DATA = path.join(ROOT, "platform/data");

function loadData() {
  const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
  const files = ["curriculum.js", "storytelling.js"].concat(
    fs.readdirSync(DATA).filter(f => /^summaries-.*\.js$/.test(f)).sort());
  files.forEach(f => vm.runInContext(fs.readFileSync(path.join(DATA, f), "utf8"), ctx, { filename: f }));
  return ctx.DAR;
}
const D = loadData();

// ---------- every lecture ----------
const lectures = [];
for (const c of D.COURSES) {
  (c.units || []).forEach((u, ui) => u.lessons.forEach((l, li) => {
    const key = c.id + "." + ui + "." + li;
    lectures.push({ key, cid: c.id, code: c.code, ui, unit: u.name, li, t: l.t, v: l.v || "", min: l.min || 0, s: D.SUMMARIES[key] || null });
  }));
}
const byKey = Object.fromEntries(lectures.map(x => [x.key, x]));

if (process.argv.includes("--check-prereqs")) { checkPrereqs(); return; }

// ---------- text → weighted tokens ----------
const STOP = new Set(("a an the and or of to in on for with by from at as is are was were be been being it its this that these those " +
  "you your we our they their he she his her them i me my not no but if then than so do does did can could will would should " +
  "into out up down over under about after before more most less least very just only also how what why when where which who whom " +
  "one two three four five six first second each every all any some same other another such own lecture video chapter part " +
  "use used using uses make makes made get gets take takes way ways thing things here there now new show shows shown see seen " +
  "look like much many may might must need needs give gives given go goes say says said let lets end ends start starts course " +
  "unit lesson talk mit example examples point points idea ideas case cases good well back kind number numbers time times").split(/\s+/));
function stem(w) {
  if (w.length > 5) w = w.replace(/(ations|ation|ings|ing|ies|ied|ness|ments|ment|ers|er|es|ed|ly|s)$/, "");
  return w;
}
function tokens(text) {
  return String(text || "")
    .replace(/\$[^$]*\$/g, " ")            // drop inline maths
    .replace(/\\[a-zA-Z]+/g, " ")
    .toLowerCase().replace(/[^a-z0-9\s-]/g, " ").split(/[\s-]+/)
    .filter(w => w.length > 2 && !STOP.has(w) && !/^\d+$/.test(w)).map(stem).filter(w => w.length > 2 && !STOP.has(w));
}
function docText(x) {
  const parts = [x.t, x.t];               // the title counts twice
  if (x.s) {
    parts.push(x.s.takeaway || "");
    (x.s.beats || []).forEach(b => parts.push(b.t || "", b.d || ""));
  }
  return parts.join(" ");
}
const tf = lectures.map(x => {
  const m = new Map();
  tokens(docText(x)).forEach(w => m.set(w, (m.get(w) || 0) + 1));
  return m;
});
const df = new Map();
tf.forEach(m => m.forEach((_, w) => df.set(w, (df.get(w) || 0) + 1)));
const N = lectures.length;
const vecs = tf.map(m => {
  const v = new Map(); let norm = 0;
  m.forEach((c, w) => { const x = (1 + Math.log(c)) * Math.log(N / df.get(w)); v.set(w, x); norm += x * x; });
  norm = Math.sqrt(norm) || 1;
  v.forEach((x, w) => v.set(w, x / norm));
  return v;
});
function cos(a, b) {
  let s = 0; const [p, q] = a.size < b.size ? [a, b] : [b, a];
  p.forEach((x, w) => { const y = q.get(w); if (y) s += x * y; });
  return s;
}
function shared(a, b, n) {
  const out = [];
  a.forEach((x, w) => { const y = b.get(w); if (y) out.push([w, x * y]); });
  return out.sort((p, q) => q[1] - p[1] || (p[0] < q[0] ? -1 : 1)).slice(0, n).map(p => p[0]).join(" ");
}

// ---------- output ----------
const out = [];
const P = s => out.push(s);
P("# audit-raw.txt — generated by tools/audit-lectures.js (read-only). Do not edit by hand.");
P("# Lectures: " + lectures.length + "; with a summary: " + lectures.filter(x => x.s).length);
P("");
P("## Totals per course");
for (const c of D.COURSES) {
  const ls = lectures.filter(x => x.cid === c.id);
  const min = ls.reduce((a, x) => a + x.min, 0);
  P(`${c.code.padEnd(9)} ${c.id.padEnd(8)} lectures ${String(ls.length).padStart(3)}  minutes ${String(min).padStart(5)} (${(min / 60).toFixed(1)} h)  summaries ${ls.filter(x => x.s).length}${c.elective ? "  [elective]" : ""}  — ${c.title}`);
}
P("");
P("## Same YouTube id used by more than one lesson key");
const byV = new Map();
lectures.forEach(x => { if (x.v) byV.set(x.v, (byV.get(x.v) || []).concat(x.key)); });
let dupV = 0;
byV.forEach((keys, v) => { if (keys.length > 1) { dupV++; P(`${v}  ${keys.join(", ")}`); } });
if (!dupV) P("(none)");
P("");
P("## Every lecture: key | course | min | title | takeaway");
let lastUnit = "";
for (const x of lectures) {
  const u = x.cid + "." + x.ui;
  if (u !== lastUnit) { P(""); P(`### ${x.code} — ${x.unit}`); lastUnit = u; }
  P(`${x.key} | ${x.code} | ${x.min} | ${x.t} | ${x.s ? x.s.takeaway : "(no summary)"}`);
}

// Pairs. Within one course, consecutive lectures sharing words is expected (they
// build on each other), so the within-course list skips immediate neighbours
// and keeps the strongest pairs; the cross-course list is where repetition
// between sources (3B1B vs MIT, Karpathy vs CS336) shows up.
const pairs = [];
for (let i = 0; i < N; i++) for (let j = i + 1; j < N; j++) {
  const s = cos(vecs[i], vecs[j]);
  if (s >= 0.18) pairs.push({ i, j, s });
}
pairs.sort((a, b) => b.s - a.s || a.i - b.i || a.j - b.j);
const fmt = p => `${p.s.toFixed(3)}  ${lectures[p.i].key} "${lectures[p.i].t}"  <->  ${lectures[p.j].key} "${lectures[p.j].t}"  [${shared(vecs[p.i], vecs[p.j], 6)}]`;
const adjacent = p => lectures[p.i].cid === lectures[p.j].cid && lectures[p.i].ui === lectures[p.j].ui && Math.abs(lectures[p.i].li - lectures[p.j].li) === 1;

P(""); P("## Candidate overlaps ACROSS courses (cosine >= 0.18, strongest first, at most 150)");
pairs.filter(p => lectures[p.i].cid !== lectures[p.j].cid).slice(0, 150).forEach(p => P(fmt(p)));

P(""); P("## Candidate overlaps WITHIN a course, excluding SPCH 100 (non-adjacent, cosine >= 0.25, at most 120)");
pairs.filter(p => lectures[p.i].cid === lectures[p.j].cid && lectures[p.i].cid !== "spch100" && !adjacent(p) && p.s >= 0.25).slice(0, 120).forEach(p => P(fmt(p)));

P(""); P("## Candidate overlaps WITHIN SPCH 100 (any two lessons, cosine >= 0.30, at most 120)");
pairs.filter(p => lectures[p.i].cid === "spch100" && lectures[p.j].cid === "spch100" && p.s >= 0.30).slice(0, 120).forEach(p => P(fmt(p)));

P(""); P("## Adjacent lessons within a unit with cosine >= 0.40 (often a two-part lecture; listed for completeness)");
pairs.filter(p => adjacent(p) && p.s >= 0.40).forEach(p => P(fmt(p)));

process.stdout.write(out.join("\n") + "\n");

// ---------- prerequisites.json validation ----------
function checkPrereqs() {
  const fp = path.join(ROOT, "loop/specs/T-067-plan-v2/prerequisites.json");
  const map = JSON.parse(fs.readFileSync(fp, "utf8"));
  const prov = map._provisional || {};
  const nodes = Object.keys(map).filter(k => !k.startsWith("_"));
  const real = new Set(lectures.map(x => x.key));
  let bad = 0;
  const err = m => { bad++; console.log("FAIL  " + m); };
  // every existing lecture present
  lectures.forEach(x => { if (!map[x.key]) err("missing entry for existing lecture " + x.key); });
  nodes.forEach(k => {
    if (!real.has(k) && !prov[k]) err("key is neither real nor declared provisional: " + k);
    const e = map[k];
    if (![1, 2, 3].includes(e.level)) err("bad level on " + k);
    (e.needs || []).forEach(n => { if (!map[n]) err(k + " needs unknown key " + n); if (n === k) err(k + " needs itself"); });
  });
  // cycle check (iterative DFS, colours)
  const colour = {}; let cycles = 0;
  for (const start of nodes) {
    if (colour[start]) continue;
    const stack = [[start, 0]]; colour[start] = 1; const trail = [start];
    while (stack.length) {
      const top = stack[stack.length - 1];
      const needs = map[top[0]].needs || [];
      if (top[1] < needs.length) {
        const n = needs[top[1]++];
        if (!map[n]) continue;
        if (colour[n] === 1) { cycles++; err("cycle: " + trail.slice(trail.indexOf(n)).concat(n).join(" -> ")); }
        else if (!colour[n]) { colour[n] = 1; stack.push([n, 0]); trail.push(n); }
      } else { colour[top[0]] = 2; stack.pop(); trail.pop(); }
    }
  }
  console.log(`prerequisites.json: ${nodes.length} entries (${nodes.filter(k => real.has(k)).length} real, ${nodes.filter(k => !real.has(k)).length} provisional), ${nodes.reduce((a, k) => a + (map[k].needs || []).length, 0)} edges, ${cycles} cycles, ${bad} failures`);
  process.exitCode = bad ? 1 : 0;
}
