// crest-gen.js — writes the Brickford crest everywhere it appears, from the one
// master drawing, platform/icons/crest.svg (viewBox 0 0 200 224, one even-odd path).
//   platform/index.html   the sidebar/drawer crest: <path class="cr-mark">, coloured by CSS (--crest)
//   app/web/index.html    the phone app's boot crest, in the brand gold
//   app/lib/widgets/crest_data.dart   the same path data for the Flutter painter
//   platform/icons/*.png, app/web/icons/*.png, app/web/favicon.png
//                         every icon: the browser tab (16/32/48), the iPhone home screen
//                         (apple-touch-icon, 180, opaque), Android/Chrome (192, 512, maskable 512)
// Usage: node tools/crest-gen.js   (then bump the ?v= token so phones fetch the new icons)
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const P = (...a) => path.join(ROOT, ...a);

const master = fs.readFileSync(P("platform/icons/crest.svg"), "utf8");
const D = (/ d="([^"]+)"/.exec(master) || [])[1];
if (!D) throw new Error("no path in platform/icons/crest.svg");
const GOLD = "#DFB46B", GROUND = "#090909";   // the artwork's own gold and black

function swapSvg(file, svg, marker) {
  const s = fs.readFileSync(file, "utf8");
  const i = s.indexOf(marker);
  if (i < 0) throw new Error(file + ": no " + marker);
  const j = s.indexOf("</svg>", i);
  fs.writeFileSync(file, s.slice(0, i) + svg + s.slice(j + 6));
}

// 1. The web app's crest: coloured by its theme (.crest .cr-mark { fill: var(--crest) }).
swapSvg(P("platform/index.html"),
  '<svg viewBox="0 0 200 224" aria-label="Brickford crest"><path class="cr-mark" fill-rule="evenodd" d="' + D + '"/></svg>',
  '<svg viewBox="0 0 200 224" aria-label="Brickford crest">');
// 2. The phone app's boot screen: the brand gold on midnight.
swapSvg(P("app/web/index.html"),
  '<svg viewBox="0 0 200 224" role="img" aria-label="Brickford crest"><path fill="' + GOLD + '" fill-rule="evenodd" d="' + D + '"/></svg>',
  '<svg viewBox="0 0 200 224" role="img" aria-label="Brickford crest">');
// 3. Flutter: the same path data.
fs.writeFileSync(P("app/lib/widgets/crest_data.dart"),
  "// GENERATED by tools/crest-gen.js from platform/icons/crest.svg (viewBox 0 0 200 224):\n" +
  "// the crest as one even-odd path, absolute M/L/C/Z only. Regenerate rather than edit.\n" +
  "const crestPathData =\n    '" + D + "';\n");

// 4. Every icon, rendered by Chromium from the same path.
(async () => {
  const { chromium } = require("playwright");
  const b = await chromium.launch();
  const page = await b.newPage();
  // h: the crest's height as a share of the square; ground: opaque black, or none.
  const render = async (out, size, h) => {
    const ch = size * h, cw = ch * 200 / 224;
    await page.setViewportSize({ width: size, height: size });
    await page.setContent('<html><body style="margin:0;width:' + size + 'px;height:' + size + 'px;background:' + GROUND + ';overflow:hidden">' +
      '<svg viewBox="0 0 200 224" style="position:absolute;left:' + (size - cw) / 2 + 'px;top:' + (size - ch) / 2 + 'px;width:' + cw + 'px;height:' + ch + 'px">' +
      '<path fill="' + GOLD + '" fill-rule="evenodd" d="' + D + '"/></svg></body></html>');
    for (const o of [].concat(out)) await page.screenshot({ path: P(o), omitBackground: false });
  };
  // Home screens and installs: the crest at 80% on the artwork's black (opaque: iOS
  // composites any transparency onto black, and a crest with room around it reads as an icon).
  await render(["platform/icons/apple-touch-icon.png", "app/web/icons/apple-touch-icon.png"], 180, 0.80);
  await render(["platform/icons/icon-192.png", "app/web/icons/icon-192.png"], 192, 0.80);
  await render(["platform/icons/icon-512.png", "app/web/icons/icon-512.png"], 512, 0.80);
  // Android's adaptive mask may crop to a circle: keep the crest inside the middle ~62%.
  await render(["platform/icons/icon-maskable-512.png", "app/web/icons/icon-maskable-512.png"], 512, 0.62);
  // The browser tab: as large as the square allows, on black so it reads on a light tab bar too.
  await render(["platform/icons/favicon-48.png", "app/web/icons/favicon-48.png"], 48, 0.94);
  await render(["platform/icons/favicon-32.png", "app/web/favicon.png"], 32, 0.94);
  await render(["platform/icons/favicon-16.png", "app/web/icons/favicon-16.png"], 16, 0.94);
  await b.close();
  console.log("crest-gen: 3 sources and 13 icons written from platform/icons/crest.svg");
})().catch(e => { console.error(e); process.exit(1); });
